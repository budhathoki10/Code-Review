/**
 * Scenario definitions for the large-PR runbook.
 *
 * Each scenario produces two file trees: a BASE state and a HEAD state. The
 * harness commits the base to one branch and the head to another, then opens
 * a PR between them — which is what makes files come back from GitHub with
 * status `modified` rather than `added`. A PR of purely added files exercises
 * a different (easier) path than the one these scenarios are meant to test.
 *
 * Sizes here are chosen to land on specific sides of the pipeline's real
 * thresholds (see REVIEW_CAPACITY in diff-selection.ts). If those constants
 * change, `predict.ts` will report the new expected values rather than these
 * comments going stale.
 */

export interface Scenario {
  id: number;
  slug: string;
  title: string;
  /** What this scenario is actually testing — printed in the report. */
  intent: string;
  /** Files as they exist on the PR's base branch. */
  base: Record<string, string>;
  /** Files as they exist on the PR's head branch. */
  head: Record<string, string>;
  /** Scenario 4 layers a second push onto an already-reviewed PR. */
  followUp?: Record<string, string>;
  expect: {
    /** Whether the size gate should refuse this PR outright. */
    bails: boolean;
    /** Zero LLM calls expected (either a bail, or nothing survived filtering). */
    zeroLlmCalls: boolean;
    notes: string[];
  };
}

/** A plausible TypeScript module of roughly `lines` lines. */
function sourceFile(name: string, lines: number, variant: number): string {
  const out = [
    `// ${name} — generated fixture for the large-PR verification runbook`,
    `export interface Config${variant} {`,
    `  retries: number;`,
    `  timeoutMs: number;`,
    `}`,
    ``,
  ];
  for (let i = 0; i < lines; i++) {
    out.push(`export function handler${variant}_${i}(input: number): number {`);
    out.push(`  const scaled = input * ${variant + i + 1};`);
    out.push(`  return scaled > 0 ? scaled : ${variant};`);
    out.push(`}`);
  }
  return out.join("\n") + "\n";
}

/** The same module with every function body changed — a real diff, not a reformat. */
function sourceFileChanged(name: string, lines: number, variant: number): string {
  const out = [
    `// ${name} — generated fixture for the large-PR verification runbook`,
    `export interface Config${variant} {`,
    `  retries: number;`,
    `  timeoutMs: number;`,
    `}`,
    ``,
  ];
  for (let i = 0; i < lines; i++) {
    out.push(`export function handler${variant}_${i}(input: number): number {`);
    out.push(`  const scaled = input * ${variant + i + 2};`);
    out.push(`  return scaled >= 0 ? scaled + 1 : ${variant + 1};`);
    out.push(`}`);
  }
  return out.join("\n") + "\n";
}

function tree(
  count: number,
  make: (name: string, index: number) => string,
  prefix = "src/mod",
): Record<string, string> {
  const files: Record<string, string> = {};
  for (let i = 0; i < count; i++) {
    const name = `${prefix}${i}.ts`;
    files[name] = make(name, i);
  }
  return files;
}

/** A lockfile large enough to dominate the diff if it were ever reviewed. */
function lockfile(entries: number, bump: number): string {
  const deps: Record<string, unknown> = {};
  for (let i = 0; i < entries; i++) {
    deps[`node_modules/pkg-${i}`] = {
      version: `1.0.${i + bump}`,
      resolved: `https://registry.npmjs.org/pkg-${i}/-/pkg-${i}-1.0.${i + bump}.tgz`,
      integrity: `sha512-${"a".repeat(40)}${i}`,
    };
  }
  return JSON.stringify({ name: "fixture", lockfileVersion: 3, packages: deps }, null, 2) + "\n";
}

function generatedFile(lines: number, bump: number): string {
  const out = [
    "// Code generated by protoc-gen-ts. DO NOT EDIT.",
    "// @generated",
    "",
  ];
  for (let i = 0; i < lines; i++) out.push(`export const FIELD_${i} = ${i + bump};`);
  return out.join("\n") + "\n";
}

