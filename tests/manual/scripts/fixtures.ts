export function scenarioById(id: number): Scenario {
  const found = SCENARIOS.find((s) => s.id === id);
  if (!found) throw new Error(`no scenario ${id} (have ${SCENARIOS.map((s) => s.id).join(", ")})`);
  return found;
}
